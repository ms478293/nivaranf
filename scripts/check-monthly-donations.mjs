import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { randomBytes, randomUUID } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
const dir = mkdtempSync(join(tmpdir(), "nivaran-payment-test-"));
process.env.DONATION_DATA_DIR = dir;
process.env.DONATION_ENCRYPTION_KEY = randomBytes(32).toString("hex");
const s = await import("../src/lib/donations/store.mjs");
try {
  assert.equal(s.nextMonthlyDate("2025-01-31T12:00:00.000Z", "2025-01-31T12:00:00.000Z"), "2025-02-28T12:00:00.000Z");
  assert.equal(s.nextMonthlyDate("2024-01-31T12:00:00.000Z", "2024-01-31T12:00:00.000Z"), "2024-02-29T12:00:00.000Z");
  assert.equal(s.nextMonthlyDate("2025-01-31T12:00:00.000Z", "2025-02-28T12:00:00.000Z"), "2025-03-31T12:00:00.000Z");
  assert.equal(s.nextMonthlyDate("2025-01-31T12:00:00.000Z", "2025-12-31T12:00:00.000Z"), "2026-01-31T12:00:00.000Z");
  assert.equal(s.nextMonthlyDate("2025-01-31T12:00:00.000Z", "2026-06-20T00:00:00.000Z"), "2026-06-30T12:00:00.000Z");
  const id = randomUUID(), p = { paymentToken: "not-a-real-token-encryption-check", email: "test@example.invalid", totalCents: 3000, anchor: "2025-01-31T12:00:00.000Z" };
  assert.equal(s.claimAttempt(id, "a").claimed, true);
  assert.equal(s.claimAttempt(id, "a").claimed, false);
  assert.equal(s.claimAttempt(id, "b").conflict, true);
  s.prepareSubscription(id, p);
  s.finishAttempt(id, "approved", { totalCents: 3000 }, id, "2025-02-28T12:00:00.000Z");
  assert.deepEqual(s.claimAttempt(id, "a").result, { totalCents: 3000 });
  assert.equal(s.claimDue("2025-02-27T12:00:00.000Z"), null);
  const due = s.claimDue("2025-02-28T12:00:00.000Z");
  assert.equal(due.id, id);
  assert.equal(s.claimDue("2025-02-28T12:00:00.000Z"), null, "No duplicate renewal during concurrent runs");
  s.finishAttempt(due.attemptId, "review", {}, id);
  assert.equal(s.claimDue("2025-03-31T12:00:00.000Z"), null, "Unknown outcomes never auto-retry");
  const token = s.managementToken(id);
  assert.equal(s.verifiedId(token), id);
  assert.equal(s.verifiedId(token.slice(0, -1) + (token.endsWith("A") ? "B" : "A")), null);
  assert.equal(s.verifiedId("garbage"), null);
  assert.equal(s.cancelSubscription(id), true);
  assert.equal(s.getSubscription(id).payload.paymentToken, undefined);
  s.finishAttempt(due.attemptId, "approved", {}, id, "2025-03-31T12:00:00.000Z");
  assert.equal(s.getSubscription(id).state, "cancelled", "Late success cannot undo cancellation");
  assert.equal(s.claimDue("2030-01-01T12:00:00.000Z"), null);
  const inspect = new DatabaseSync(join(dir, "donations.sqlite"));
  inspect.exec("PRAGMA wal_checkpoint(TRUNCATE)"); inspect.close();
  assert.equal(readFileSync(join(dir, "donations.sqlite")).includes(Buffer.from(p.email)), false);
  assert.equal(readFileSync(join(dir, "donations.sqlite")).includes(Buffer.from(p.paymentToken)), false);
  console.log("Monthly giving checks passed: date boundaries, idempotency, duplicate renewals, uncertain results, signed cancellation, cancellation race, encrypted storage.");
} finally { rmSync(dir, { recursive: true, force: true }); }
